alter table public.eventora_settings enable row level security;
alter table public.event_segment_prices enable row level security;

revoke all on public.eventora_settings from anon, authenticated;
grant select, update on public.eventora_settings to authenticated;

drop policy if exists "Admins read EVENTORA settings" on public.eventora_settings;
create policy "Admins read EVENTORA settings" on public.eventora_settings
for select to authenticated using ((select public.is_eventora_admin()));

drop policy if exists "Admins update EVENTORA settings" on public.eventora_settings;
create policy "Admins update EVENTORA settings" on public.eventora_settings
for update to authenticated using ((select public.is_eventora_admin()))
with check ((select public.is_eventora_admin()));

revoke all on public.event_segment_prices from anon, authenticated;
grant select on public.event_segment_prices to anon, authenticated;
grant insert, update, delete on public.event_segment_prices to authenticated;

drop policy if exists "Public can view segment prices" on public.event_segment_prices;
create policy "Public can view segment prices" on public.event_segment_prices
for select to anon, authenticated using (true);

drop policy if exists "Admins manage segment prices" on public.event_segment_prices;
create policy "Admins manage segment prices" on public.event_segment_prices
for all to authenticated using ((select public.is_eventora_admin()))
with check ((select public.is_eventora_admin()));

create or replace function public.is_early_bird_active()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.eventora_settings
    where id = 1
      and early_bird_deadline is not null
      and now() < early_bird_deadline
  );
$$;

revoke all on function public.is_early_bird_active() from public;
grant execute on function public.is_early_bird_active() to anon, authenticated;

-- The public function exposes only active/inactive, never the deadline timestamp.
