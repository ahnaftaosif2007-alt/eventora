-- EVENTORA pricing and Early Bird settings migration
-- Run after supabase/schema.sql in Supabase Dashboard -> SQL Editor.

create table if not exists public.eventora_settings (
  id smallint primary key default 1 check (id = 1),
  early_bird_deadline timestamptz,
  club_member_discount numeric(5,2) not null default 15.00 check (club_member_discount between 0 and 100),
  early_bird_discount numeric(5,2) not null default 20.00 check (early_bird_discount between 0 and 100),
  membership_fee numeric(10,2) not null default 100.00 check (membership_fee >= 0),
  updated_at timestamptz not null default now()
);

insert into public.eventora_settings (id)
values (1)
on conflict (id) do nothing;

create table if not exists public.event_segment_prices (
  id bigint generated by default as identity primary key,
  segment text not null,
  division text not null check (division in ('A','B','C')),
  price numeric(10,2) not null check (price >= 0),
  unique (segment, division)
);

